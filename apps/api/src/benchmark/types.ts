import type { ImpactStatus } from '../analysis/impact/types.js';

/**
 * `control` -- slice 4's original 44 hand-written fixtures, each shaped
 * closely around a single predicate/applicability behavior.
 * `realistic` -- slice 5's fixtures, shaped like ordinary production
 * TypeScript (nested directories, destructuring, class-based services,
 * partial migrations, cross-file layering) rather than around the
 * analyser's own capabilities -- see docs/impact-analysis.md's Realistic
 * validation section. Reported separately so a perfect control-corpus
 * score can never hide weaker realistic-corpus behavior.
 */
export type Corpus = 'control' | 'realistic';

/**
 * One hand-written, hand-labelled fixture. Ground truth is authored and
 * reviewed like any other code -- never generated by running the analyser
 * being evaluated, and never persisted to the production database (see
 * docs/impact-analysis.md's Evaluation approach section).
 */
export interface BenchmarkCase {
  id: string;
  ruleExternalId: string;
  category: 'POSITIVE' | 'NEGATIVE' | 'UNCERTAIN';
  corpus: Corpus;
  /** file path -> file content, fed directly into ExtractedFile[] (no tar round-trip). */
  files: Record<string, string>;
  expected: {
    status: ImpactStatus;
    findingCount?: number;
    findingLocations?: { sourceFile: string; line: number }[];
  };
  /** Why this case exists and what it's meant to prove/reject. */
  notes: string;
}

/**
 * Classification of one case's (expected, actual) pair. Named to make the
 * safety-critical buckets impossible to miss in code that consumes them --
 * see docs/impact-analysis.md's Evaluation approach for the full
 * expected-vs-actual table this implements.
 */
export type OutcomeBucket =
  | 'TRUE_POSITIVE'
  | 'TRUE_NEGATIVE'
  | 'CORRECT_ABSTENTION'
  | 'FALSE_NOT_AFFECTED_SAFETY_FAILURE'
  | 'OVER_ABSTENTION'
  | 'FALSE_POSITIVE'
  | 'UNSAFE_CERTAINTY';

export interface CaseOutcome {
  case: BenchmarkCase;
  actualStatus: ImpactStatus;
  bucket: OutcomeBucket;
  /** Only meaningful for AFFECTED cases that specify expectedLocations. */
  findingLocationsCorrect: boolean | null;
}

export interface AggregateMetrics {
  totalCases: number;
  truePositives: number;
  trueNegatives: number;
  correctAbstentions: number;
  falseNotAffectedSafetyFailures: number;
  overAbstentions: number;
  falsePositives: number;
  unsafeCertaintyCount: number;
  precisionAffected: number | null;
  recallAffected: number | null;
  findingLocationAccuracy: { correct: number; total: number } | null;
}

export interface RuleReport extends AggregateMetrics {
  ruleExternalId: string;
  title: string;
}

export interface BenchmarkReport {
  totalRules: number;
  totalCases: number;
  overall: AggregateMetrics;
  /** Same metrics, split by control vs. realistic corpus -- see Corpus above. */
  byCorpus: Record<Corpus, AggregateMetrics>;
  perRule: RuleReport[];
  caseOutcomes: CaseOutcome[];
}
